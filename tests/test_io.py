def test_fixtures_are_exactly_what_the_generator_writes(
    generator: ModuleType, tmp_path: Path
) -> None:
    """The committed CSVs are synthetic output, byte-reproducible from a seed.

    This is the licensing guarantee as well as a determinism check: every byte
    under ``tests/fixtures/metrica`` comes out of the committed generator and a
    fixed PRNG seed, so none of it can be Metrica match data.
    """
    for game in generator.GAMES:
        generator.generate(game, tmp_path)

    committed = sorted(FIXTURES.rglob("*.csv"))
    assert len(committed) == 6, "three CSVs per game"
    for path in committed:
        rebuilt = tmp_path / path.relative_to(FIXTURES)
        assert rebuilt.read_bytes() == path.read_bytes(), f"{path.name} is not reproducible"


def test_every_documented_quirk_is_still_in_the_fixtures(generator: ModuleType) -> None:
    """A generator that emitted clean data would silently retire these tests."""
    evidence = generator.verify(FIXTURES)
    assert set(evidence) == set(generator.QUIRKS)
    assert all(evidence.values()), "every quirk must come back with its evidence"


