"""Tests for the Metrica loaders in :mod:`pressing._io`.

Every test runs offline against the synthetic Metrica-shaped CSVs under
``tests/fixtures/metrica`` or against tiny Metrica-shaped files written to
``tmp_path``. Nothing here reaches the network or the full 120 MB cache.

The fixtures are generated by ``tests/fixtures/make_metrica_fixtures.py`` and
carry no Metrica match data; they reproduce the container and every parsing
quirk instead. The frame numbers asserted below are that generator's, so if it
changes, ``QUIRKS`` there and these constants move together.
"""

from __future__ import annotations

import csv
